// Command buildnumber считает номер сборки gophkeeper в форме Apple и
// пишет его в файл отдельной строкой.
//
//	go run ./tools/buildnumber <файл> <версия>
//
// Версия приходит из GoReleaser. Для dev номер равен dev. Для выпуска номер
// состоит из мажора, буквы минора и числа коммитов после базы, например
// 27A41. База это старший тег вида X.Y ниже текущей пары мажора и минора.
// Бета получает после буквы цифру 5, счётчик из трёх цифр и строчную букву
// своего номера, например 27B5012b. Кандидат выглядит как выпуск. Ступень
// кроме beta и rc, минор больше 25 или бета больше 26 дают ошибку.
