// Command sandbox готовит окружение для проверки клиента GophKeeper.
//
//	go run ./cmd/sandbox <команда>
//
// Команда up запускает в фоне локальную песочницу с очередью изменений и её
// обработчиком и записывает настройки клиента. С флагом own она вместо
// облачного Supabase запускает собственный сервер GophKeeper и Postgres в
// Docker и вызывается из корня репозитория. При первом таком запуске она
// создаёт ключ подписи токенов входа и хранит его до команды reset. Команда down останавливает
// песочницу, сохраняя её данные, а reset останавливает песочницу и удаляет её
// данные и настройки.
// Команда cloud подключает клиент к облачным Supabase и очереди изменений.
//
// Запуск без команды печатает список команд.
