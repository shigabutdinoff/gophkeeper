// Command gophkeeperd обслуживает сервер GophKeeper.
//
//	gophkeeperd server [флаги]
//	gophkeeperd worker [флаги]
//
// Команда server принимает запросы клиентов по защищённому соединению с
// сертификатом и ключом сервера и отказывает запросам без ключа проекта.
// Она регистрирует пользователей и выполняет вход, хранит учётные записи в
// базе данных Postgres, сама создаёт в ней таблицы и подписывает токены входа
// ключом ECDSA P-256 из файла PEM. Без базы или ключа она не запускается.
// Переменная GIN_MODE допускает только значения debug, release и test.
// Соединение без целого запроса она закрывает через 30 секунд.
// Команда worker применяет изменения из очереди изменений к серверу по одному
// в порядке прихода и отбрасывает неразборчивые. Она же пускает в очередь
// только вошедшие устройства по токену доступа. Каждое значение настроек
// берётся из переменной окружения GOPHKEEPER_*, без неё из флага, без него
// из файла настроек YAML или JSON, заданного переменной CONFIG или флагом
// config. Сигналы SIGTERM, SIGINT и SIGQUIT останавливают сервер после ответа
// на начатые запросы, а обработчик после текущего изменения.
