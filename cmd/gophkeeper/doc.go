// Command gophkeeper запускает клиент менеджера паролей GophKeeper.
//
// Клиент понимает такие команды.
//
//	gophkeeper completion <оболочка>  скрипт автодополнения
//	gophkeeper help [команда]         справка по командам
//	gophkeeper login                  вход по email и паролю
//	gophkeeper logout                 выход на этом устройстве
//	gophkeeper register               регистрация по email и паролю
//
// Адрес сервера берётся из переменной GOPHKEEPER_SERVER, затем из флага
// server, затем из файла config.yaml в каталоге настроек. Ключ приложения
// берётся только из этого файла и должен относиться к выбранному адресу.
//
// Регистрация и вход запоминают вход на этом устройстве. Ключ к данным и
// токен обновления хранятся в системном хранилище секретов, в каталоге
// настроек остаются только адрес сервера и email в файле session.yaml.
//
// Флаг version печатает версию, номер, дату и коммит сборки. Автодополнение
// есть для bash, zsh, fish и powershell. Версию, номер сборки, дату и коммит
// подставляет GoReleaser при сборке.
