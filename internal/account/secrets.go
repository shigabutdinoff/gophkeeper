package account

// Secrets содержит ключи и токен для команд с данными.
type Secrets struct {
	// Data задаёт ключ к данным.
	Data string
	// Access задаёт токен доступа к серверу и очереди. При сбое сервера
	// это последний сохранённый токен, без хранилища он пуст.
	Access string
	// User задаёт идентификатор пользователя на сервере.
	User string
	// Down задаёт причину, по которой сервер не выдал новый токен доступа.
	Down error
}
